/**
 * Build an A-ASSOCIATE-RQ PDU with the given AE titles.
 * @param called_ae  Called AE title (max 16 chars, space-padded)
 * @param calling_ae Calling AE title (max 16 chars, space-padded)
 * @param buf        Output buffer (must be at least 512 bytes)
 * @param len        Output: total PDU length written
 */
static inline void build_associate_rq(const char *called_ae, const char *calling_ae, uint8_t *buf, size_t *len) {
    size_t pos = 0;

    // PDU header: type (1) + reserved (1) + length (4)
    buf[pos++] = 0x01; // PDU type: A-ASSOCIATE-RQ
    buf[pos++] = 0x00; // Reserved

    // Skip length field for now (4 bytes), fill later
    size_t length_pos = pos;
    pos += 4;

    // Protocol version: 1
    buf[pos++] = 0x00;
    buf[pos++] = 0x01;

    // Reserved (2 bytes)
    buf[pos++] = 0x00;
    buf[pos++] = 0x00;

    // Called AE Title (16 bytes, space-padded)
    memset(buf + pos, 0x20, 16);
    size_t ae_len = strlen(called_ae);
    if (ae_len > 16) ae_len = 16;
    memcpy(buf + pos, called_ae, ae_len);
    pos += 16;

    // Calling AE Title (16 bytes, space-padded)
    memset(buf + pos, 0x20, 16);
    ae_len = strlen(calling_ae);
    if (ae_len > 16) ae_len = 16;
    memcpy(buf + pos, calling_ae, ae_len);
    pos += 16;

    // Reserved (32 bytes)
    memset(buf + pos, 0x00, 32);
    pos += 32;

    // Append the items (application context, presentation contexts, user info)
    memcpy(buf + pos, a_associate_rq_items, sizeof(a_associate_rq_items));
    pos += sizeof(a_associate_rq_items);

    // Fill in the PDU length field (total length minus the 6-byte header)
    uint32_t pdu_body_len = pos - 6;
    buf[length_pos]     = (pdu_body_len >> 24) & 0xFF;
    buf[length_pos + 1] = (pdu_body_len >> 16) & 0xFF;
    buf[length_pos + 2] = (pdu_body_len >> 8)  & 0xFF;
    buf[length_pos + 3] =  pdu_body_len        & 0xFF;

    *len = pos;
}

// Forward declare the context struct
typedef struct inject_dicom_context_struct inject_dicom_context_t;

// Define the struct with exposed fields for tracking statistics
struct inject_dicom_context_struct {
    int client_fd;
    uint16_t nb_copies;
    const char *host;
    uint16_t port;
    bool shown_error;
    size_t total_sent_pkt;
    size_t total_pkt_to_send;
    size_t total_dropped_pkt;
    size_t total_rejected_connections;
    char last_error_message[4096]; // Use same size as BUFFER_SIZE in .c file
    int last_response_code;
    bool found_patient_results; // Flag to track if patient search results were found

    // Fields for tracking AE titles
    char current_calling_ae_title[17]; // Current AE Title being tried
    char last_successful_ae_title[17]; // The last AE Title that was accepted

    // Dynamically built A-ASSOCIATE-RQ PDU
    uint8_t *associate_rq;
    size_t associate_rq_len;
};

